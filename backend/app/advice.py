def get_suggestion(disease_label: str, disease_name: str | None, supported: bool) -> str:
    """按病害名取内置建议；不支持的作物给出范围说明。"""
    if not supported:
        return _UNSUPPORTED
    if disease_label == "healthy":
        return _ADVICE["healthy"]
    text = _GENERIC
    if disease_name:
        low = disease_name.lower()
        for kw, advice in _ADVICE.items():
            if kw in low:
                text = advice
                break
    return f"检测到{_display_name(disease_name)}。{text}课程原型仅供参考，请以专业植保意见为准。"


def _display_name(name: str | None) -> str:
    """建议文案里的病名用中文展示；匹配仍用英文原名，这里只管显示。"""
    from .predict import disease_zh
    return disease_zh(name) or "疑似病害"


# ---- 识别 → 嫁接联动 ----
# 这些病害族的病原在土壤/残体上越冬，重茬反复发作，叶面喷药治标不治本；
# 生产上的标准对策是换抗病砧木重新嫁接（番茄→托鲁巴姆等）。
# 注：PlantVillage 38 类里没有青枯/枯萎/根腐结论，细菌性斑点（Bacterial Spot）
# 是模型能落地的唯一细菌性病害，同族病害的田间管理与砧木方案一致，故纳入触发。
SOIL_BORNE_KEYWORDS = ("bacterial", "wilt", "root")

GRAFT_REASON = (
    "{crop}的这类病害若反复发生，病原多半已在土壤或残体上越冬，叶面喷药够不到，"
    "重茬只会一年比一年重。生产上的标准做法不是打药，而是换根：用抗病砧木重新嫁接，"
    "让植株长在无病的砧根上，地上部分照常结果。下面是适配 {crop} 的砧木，"
    "可以在嫁接初筛里试算兼容性。"
)


def is_soil_borne(disease_name: str | None) -> bool:
    """病害英文名是否属于砧木嫁接适用的土传/维管束族（按关键词匹配，与建议文案同路）。"""
    if not disease_name:
        return False
    low = disease_name.lower()
    return any(k in low for k in SOIL_BORNE_KEYWORDS)


def graft_reason(crop: str) -> str:
    return GRAFT_REASON.format(crop=crop)
