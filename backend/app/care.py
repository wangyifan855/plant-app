def get_care(crop: str | None) -> dict:
    """按作物英文键取照养知识，未收录时回退通用版。"""
    if crop and crop in CARE:
        return dict(CARE[crop], crop=crop)
    return dict(FALLBACK, crop=crop)


def crop_from_species_label(label: str | None) -> str | None:
    """从物种识别结果（如「番茄 (Tomato)」）推断作物英文键。"""
    if not label:
        return None
    for en, info in CARE.items():
        if info["zh"] in label or en.lower() in label.lower():
            return en
    return None
